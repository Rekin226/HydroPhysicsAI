    ap.add_argument("--ref-q0c", default=REF["q0c"])
    ap.add_argument("--ref-x5r1", default=REF["x5r1"])
    ap.add_argument("--attempts", default=DEFAULT_ATTEMPTS)
    ap.add_argument("--out", default=None, help="report JSON (scoring mode; required there)")
    ap.add_argument("--check-shapes", action="store_true",
                    help="plumbing check on the batch-27 files (baseline, cut30): steps 1-2 only")
    ap.add_argument("--verify-registration", action="store_true",
                    help="step 0 only (registration and frozen code); reads no npz")
    a = ap.parse_args(argv)
    if _rows_sha() != ROWS_SHA256:
        raise SystemExit("frozen well list was edited (rows sha mismatch)")
    if len(CELLS) != 158 or "".join(COUNTY).count("C") != 74:
        raise SystemExit("frozen well list is not 158 screens / 74 Changhua")
    scoring = not a.check_shapes
    reg = None
    try:
        if scoring:
            if not a.verify_registration and not a.out:
                raise EngineeringError("scoring mode needs --out")
            if a.out and rp(a.out).exists():
                raise EngineeringError(f"{a.out} exists: the declaration is scored once")
            doc, decl_sha = load_registered()
            frozen = check_frozen(doc)
            reg = {"declaration_sha256": decl_sha, "frozen_code_sha256": frozen}
            print(f"step 0 ok: {PREREG_ID} registered (sha256 {decl_sha[:16]}), frozen code "
                  "matches")
            if a.verify_registration:
                return 0
            reg["attempts"] = check_attempts(rp(a.attempts),
                                             {"q0c": rp(a.q0c), "x5r1": rp(a.x5r1)})
    except EngineeringError as err:
        print(f"ENGINEERING FAIL (step 0): {err}", file=sys.stderr)
        return 1
    names, descs = (SCEN_NAMES[:2], SCEN_DESC[:2]) if a.check_shapes else (SCEN_NAMES, SCEN_DESC)
    try:
        q = _load(rp(a.q0c), "q0c", names, descs)
        x = _load(rp(a.x5r1), "x5r1", names, descs)
        refs = {"q0c": _load(rp(a.ref_q0c), "q0c", SCEN_NAMES[:2], SCEN_DESC[:2]),
                "x5r1": _load(rp(a.ref_x5r1), "x5r1", SCEN_NAMES[:2], SCEN_DESC[:2])}
    except EngineeringError as err:
        print(f"ENGINEERING FAIL (step 1): {err}", file=sys.stderr)
        return 2
    rep = reproduction(q, x, refs)
    print(f"step 1 ok: {q['h'].shape[1:]} screen heads per scenario; step 2 reproduction "
          f"{'ok' if rep['ok'] else 'FAIL'}")
    for k, r in rep["entries"].items():
        print(f"  cut30 {k}: {r['ratio']:.4f} (disclosed {r['disclosed']:.4f})")
    for k, r in rep["vs_batch27"].items():
        print(f"  {k} vs batch 27: max |diff| {r['max_abs_diff_m']:.2e} m")
    if not rep["ok"]:
        print("ENGINEERING FAIL (step 2): baseline/cut30 do not reproduce batch 27; all30 "
              "not read", file=sys.stderr)
        return 3
    if a.check_shapes:
        print("check-shapes: plumbing ok; all30 not present and not computed")
        return 0
    res = score(q, x)
    report = {"prereg_id": PREREG_ID, "scorer_version": SCORER_VERSION,
              "registration": reg, "wells_rows_sha256": ROWS_SHA256,
              "files": {"q0c": {"path": q["path"], "sha256": q["sha256"]},
                        "x5r1": {"path": x["path"], "sha256": x["sha256"]}},
              "reproduction": rep, **res}
    for k, r in res["gated"].items():
        print(f"  all30 {k}: ratio {r['ratio']:.4f} (q0c {r['q0c_mean_lever_m']:.3f} m, "
              f"x5r1 {r['x5r1_mean_lever_m']:.3f} m) inside {r['inside_band']}")
    print(f"VERDICT: {res['verdict']}")
    p = rp(a.out)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("x") as f:                      # never overwrite a scored report
        json.dump(report, f, indent=1, sort_keys=True)
    print(f"wrote {a.out}")
    return 0


