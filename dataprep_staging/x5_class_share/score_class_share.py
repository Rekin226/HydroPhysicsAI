def _rows_sha() -> str:
    rows = [{"sid": s, "cell": c, "layer": k, "county": "changhua" if q == "C" else "yunlin"}
            for s, c, k, q in zip(SIDS, CELLS, LAYERS, "".join(COUNTY), strict=True)]
    return hashlib.sha256(json.dumps(rows, sort_keys=True, separators=(",", ":"))
                          .encode()).hexdigest()


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with Path(p).open("rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


class EngineeringError(RuntimeError):
    """A file or the registration is not what the declaration names; nothing is scored."""


# ----------------------------------------------------------------------------- step 0
def load_registered(prereg_dir: Path | None = None, rows_dir: Path | None = None
                    ) -> tuple[dict, str]:
    """The registered declaration, verified against INDEX.jsonl and the ledger."""
    sys.path.insert(0, str(REPO / "dataprep_staging"))
    from harness import prereg3

    kw = {}
    if prereg_dir is not None:
        kw["prereg_dir"] = prereg_dir
    if rows_dir is not None:
        kw["rows_dir"] = rows_dir
    try:
        return prereg3.load_prereg(PREREG_ID, **kw)
    except prereg3.PreregistrationError as err:
        raise EngineeringError(f"registration: {err}") from err


def check_frozen(doc: dict, repo: Path = REPO) -> dict:
    """sha256 of the scorer, the runner and wells_frozen.json against the declaration."""
    want = doc.get("frozen_code") or {}
    got = {p: sha256(repo / p) if (repo / p).exists() else "missing" for p in FROZEN}
    bad = {p: {"registered": want.get(p), "now": got[p]} for p in FROZEN
           if want.get(p) != got[p]}
    if bad:
        raise EngineeringError(f"frozen code differs from the registered declaration: {bad}")
    return got


def check_attempts(attempts: Path, files: dict[str, Path]) -> dict:
    """The npz files are the outputs of the runner's last forward attempt of each arm, which
    exited 0."""
    if not attempts.exists():
        raise EngineeringError(f"no attempt log {attempts}")
    recs = [json.loads(s) for s in attempts.read_text().splitlines() if s.strip()]
    out = {}
    for arm, p in files.items():
        fw = [r for r in recs if r.get("event") == "forward" and r.get("arm") == arm]
        if not fw:
            raise EngineeringError(f"attempt log has no forward record for {arm}")
        last = fw[-1]
        if int(last.get("rc", -1)) != 0:
            raise EngineeringError(f"last forward attempt of {arm} exited {last.get('rc')}")
        if last.get("npz_sha256") != sha256(p):
            raise EngineeringError(f"{p} is not the npz the last {arm} forward wrote")
        out[arm] = {"attempt": last.get("attempt"), "time": last.get("time"),
                    "worktree_head": last.get("worktree_head")}
    return out


# ----------------------------------------------------------------------------- step 1
def _load(path: Path, arm: str, names: tuple[str, ...], descs: tuple[str, ...]) -> dict:
    """Engineering checks, then the heads at the screens of the named scenarios only."""
    f = np.load(path, allow_pickle=False)
    e = []
    sn = tuple(str(s) for s in f["scenario_names"])
    sd = tuple(str(s) for s in f["scenarios"])
    if sn != names:
        e.append(f"scenario_names {sn} != {names}")
    if sd != descs:
        e.append(f"scenarios {sd} != {descs}")
    dates = [str(s)[:7] for s in f["dates"]]
    if len(dates) != N_T or dates[0] != "2012-01" or dates[-1] != "2032-12":
        e.append(f"dates {dates[0]}..{dates[-1]} ({len(dates)}), expected 2012-01..2032-12")
    else:
        if dates[I_CUT0] != "2026-01":
            e.append(f"dates[{I_CUT0}] = {dates[I_CUT0]}, expected 2026-01")
        for w, (a, _) in WINDOWS.items():
            if dates[a] != WINDOW_FIRST[w]:
                e.append(f"window {w} starts {dates[a]}")
    if int(f["origin"]) != ORIGIN or int(f["horizon"]) != HORIZON:
        e.append(f"origin {int(f['origin'])} horizon {int(f['horizon'])}")
    shape = f["heads_mean"].shape
    if shape != (len(names), 4, 2148, N_T):
        e.append(f"heads_mean shape {shape}")
    labels = [str(s) for s in f["member_labels"]]
    if labels != [MEMBER[arm]]:
        e.append(f"member_labels {labels} != [{MEMBER[arm]!r}]")
    if float(f["gain"]) != 1.0 or float(f["hindcast_gain"]) != 0.0:
        e.append(f"gain {float(f['gain'])} hindcast_gain {float(f['hindcast_gain'])}")
    gate = json.loads(str(f["gate"]))
    if gate.get("pump_kwh") != PUMP_KWH[arm] or gate.get("meter_filter") != METER[arm]:
        e.append(f"gate meta pump_kwh/meter_filter {gate.get('pump_kwh')}/"
                 f"{gate.get('meter_filter')}")
    if gate.get("git_commit") != THETA_GIT:
        e.append(f"theta git_commit {gate.get('git_commit')}")
    fo = json.loads(str(f["forward_options"]))
    want = {"column_heads": "free", "update_method": "innovation", "apex_hold": "calibrated",
            "restart_taper_km": 5.0, "column_hpc0_fast_days": 365.0, "save_members": "none"}
    bad = {k: fo.get(k) for k, v in want.items() if fo.get(k) != v}
    if bad:
        e.append(f"forward_options differ: {bad}")
    if e:
        raise EngineeringError(f"{path}: " + "; ".join(e))
    cells, layers = np.asarray(CELLS), np.asarray(LAYERS)
    hm = f["heads_mean"]
    # well-screen heads only: (scenario, screen, month)
    h = np.asarray(hm[:, layers, cells, :], dtype=np.float64)
    if not np.isfinite(h).all():
        raise EngineeringError(f"{path}: non-finite heads at the frozen screens")
    return {"path": str(path), "sha256": sha256(path), "names": sn, "h": h,
            "subs": np.asarray(f["subs_mean"][:, cells, :], dtype=np.float64)}


def _lever(d: dict, scen: str) -> np.ndarray:
    i = d["names"].index(scen)
    return d["h"][i] - d["h"][d["names"].index("baseline")]   # (screen, month), + = higher


def _ratio(lx: np.ndarray, lq: np.ndarray, m: np.ndarray, a: int, b: int) -> dict:
    num, den = float(lx[m, a:b].mean()), float(lq[m, a:b].mean())
    return {"x5r1_mean_lever_m": num, "q0c_mean_lever_m": den,
            "ratio": num / den if den != 0 else float("nan")}


def masks() -> dict[str, np.ndarray]:
    c = np.array(list("".join(COUNTY))) == "C"
    return {"changhua": c, "yunlin": ~c}


# ----------------------------------------------------------------------------- step 2
def reproduction(q: dict, x: dict, refs: dict | None = None) -> dict:
    """cut30 ratio against the disclosed values; with ``refs`` (the batch-27 files, loaded
    with two scenarios), baseline and cut30 heads at the screens against those files."""
    lq, lx = _lever(q, "cut30"), _lever(x, "cut30")
    rep, ok = {}, True
    for cn, m in masks().items():
        for w, (a, b) in WINDOWS.items():
            r = _ratio(lx, lq, m, a, b)
            r["disclosed"] = DISCLOSED_CUT30[cn][w]
            r["abs_diff"] = abs(r["ratio"] - r["disclosed"])
            r["ok"] = bool(np.isfinite(r["ratio"]) and r["abs_diff"] <= REPRO_TOL)
            ok &= r["ok"]
            rep[f"{cn}/{w}"] = r
    vs = {}
    if refs is not None:
        for arm, d in (("q0c", q), ("x5r1", x)):
            ref = refs[arm]
            for s in ("baseline", "cut30"):
                diff = float(np.max(np.abs(d["h"][d["names"].index(s)]
                                           - ref["h"][ref["names"].index(s)])))
                vs[f"{arm}/{s}"] = {"max_abs_diff_m": diff, "ok": diff <= REF_TOL_M,
                                    "reference": ref["path"], "reference_sha256": ref["sha256"]}
                ok &= diff <= REF_TOL_M
    return {"ok": bool(ok), "tol": REPRO_TOL, "ref_tol_m": REF_TOL_M, "entries": rep,
            "vs_batch27": vs}


# ----------------------------------------------------------------------------- step 3
def score(q: dict, x: dict) -> dict:
    lq, lx = _lever(q, "all30"), _lever(x, "all30")
    cq, cx = _lever(q, "cut30"), _lever(x, "cut30")
    gated, evaluable, inside, strict = {}, True, True, True
    for cn, m in masks().items():
        for w, (a, b) in WINDOWS.items():
            r = _ratio(lx, lq, m, a, b)
            r["evaluable"] = bool(r["q0c_mean_lever_m"] >= MIN_LEVER_M
                                  and r["x5r1_mean_lever_m"] > 0 and np.isfinite(r["ratio"]))
            r["inside_band"] = bool(r["evaluable"] and BAND[0] <= r["ratio"] <= BAND[1])
            r["inside_strict_band_report_only"] = bool(
                r["evaluable"] and STRICT_BAND[0] <= r["ratio"] <= STRICT_BAND[1])
            evaluable &= r["evaluable"]
            inside &= r["inside_band"]
            strict &= r["inside_strict_band_report_only"]
            gated[f"{cn}/{w}"] = r
    verdict = "not_evaluable" if not evaluable else ("pass" if inside else "fail")
    rs = [r["ratio"] for r in gated.values() if r["evaluable"]]
    factor = {cn: [min(1.0, *(gated[f"{cn}/{w}"]["ratio"] for w in WINDOWS)),
                   max(1.0, *(gated[f"{cn}/{w}"]["ratio"] for w in WINDOWS))]
              for cn in masks() if all(gated[f"{cn}/{w}"]["evaluable"] for w in WINDOWS)}

    rep = {}
    rep["strict_band_report_only"] = {"band": list(STRICT_BAND), "all_four_inside": strict,
                                      "note": "pre-declared; never changes the verdict"}
    rep["measured_R_range"] = [min(rs), max(rs)] if rs else None
    rep["residual_factor_by_county"] = factor        # [min(1, R), max(1, R)] over the windows
    # horizon table (the explorer's exp7 windows), both scenarios
    rep["by_horizon"] = {
        s: {cn: {k: _ratio(lx_, lq_, m, I_CUT0 + a, I_CUT0 + b)["ratio"]
                 for k, (a, b) in HORIZONS.items()}
            for cn, m in masks().items()}
        for s, lx_, lq_ in (("all30", lx, lq), ("cut30", cx, cq))}
    # irrigation fraction of the all-class lever within each model (~ irrigation share of
    # the effective volume if the response is linear in pumping)
    rep["cut30_over_all30"] = {
        arm: {cn: {w: float(c[m, a:b].mean() / al[m, a:b].mean())
                   for w, (a, b) in WINDOWS.items()} for cn, m in masks().items()}
        for arm, c, al in (("q0c", cq, lq), ("x5r1", cx, lx))}
    lay = np.asarray(LAYERS)
    rep["by_layer"] = {
        cn: {w: {f"L{k + 1}": (_ratio(lx, lq, m & (lay == k), a, b)["ratio"]
                               if (m & (lay == k)).any() else None) for k in range(4)}
             for w, (a, b) in WINDOWS.items()} for cn, m in masks().items()}
    per = {}
    for cn, m in masks().items():
        per[cn] = {}
        for w, (a, b) in WINDOWS.items():
            dq, dx = lq[m, a:b].mean(1), lx[m, a:b].mean(1)
            ok = dq >= MIN_LEVER_M
            r = dx[ok] / dq[ok]
            per[cn][w] = {"n_screens": int(ok.sum()), "n_total": int(m.sum()),
                          "median": float(np.median(r)) if r.size else None,
                          "p10": float(np.percentile(r, 10)) if r.size else None,
                          "p90": float(np.percentile(r, 90)) if r.size else None,
                          "share_inside_band": float(np.mean((r >= BAND[0]) & (r <= BAND[1])))
                          if r.size else None}
    rep["per_screen"] = per
    # subsidence lever at the same cells (cm, + = less subsidence under the cut)
    sub = {}
    for cn, m in masks().items():
        sub[cn] = {}
        for w, (a, b) in WINDOWS.items():
            vq = float((q["subs"][0] - q["subs"][q["names"].index("all30")])[m, a:b].mean())
            vx = float((x["subs"][0] - x["subs"][x["names"].index("all30")])[m, a:b].mean())
            sub[cn][w] = {"q0c_cm": vq, "x5r1_cm": vx,
                          "ratio": vx / vq if vq != 0 else None}
    rep["subsidence_all30"] = sub
    return {"verdict": verdict, "band": list(BAND), "min_lever_m": MIN_LEVER_M,
            "gated": gated, "reported_not_gating": rep}


