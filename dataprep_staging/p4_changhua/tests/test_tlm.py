def _setup(T=24, rivers=False):
    grid, m, sc = _model(rivers=rivers)
    A = grid.n_active
    E, R, ge, h0 = _forcing(A, T)
    tw = engine.SparseTwin(m, sc, ge)
    return grid, tw, E, R, ge, h0


def _rel(a, b):
    return float(np.abs(a - b).max() / np.abs(b).max())


def test_rate_factor_derivative_matches_finite_difference():
    _, tw, _, _, ge, _ = _setup()
    h = ge - np.linspace(-45.0, 30.0, ge.size)          # some lifts below the 2 m clip
    dc = engine_tlm.rate_factor_dh(tw, h)
    eps = 1e-5
    fd = (tw.rate_factor(h + eps) - tw.rate_factor(h - eps)) / (2 * eps)
    lift = ge - h + tw.hx
    ok = np.abs(lift - engine.MIN_LIFT_M) > 1e-3
    assert np.allclose(dc[ok], fd[ok], rtol=1e-7, atol=0.0)
    assert np.all(dc[lift < engine.MIN_LIFT_M] == 0.0)


@pytest.mark.parametrize("which", ["energy", "source", "rate"])
def test_tlm_matches_central_difference_of_stepwise_rollout(which):
    grid, tw, E, R, ge, h0 = _setup()
    A, T = E.shape
    rng = np.random.default_rng(11)
    Es = tw.spread(E)
    H = tw.rollout(h0, E=E, R=R)
    lifts = engine_tlm.clipped_lift_count(tw, H)
    assert lifts["n_clipped"] == 0                       # differentiable path
    eps = 1e-4
    if which == "energy":
        d = rng.uniform(0, 2e4, (A, T))
        Hp = tw.rollout(h0, E_extra=Es + eps * d, R=R, spread_extra=False)
        Hm = tw.rollout(h0, E_extra=Es - eps * d, R=R, spread_extra=False)
        dh = engine_tlm.tlm_rollout(tw, H, Es, dEs=d)
    elif which == "source":
        d = rng.standard_normal((4, A, T)) * 500.0
        Hp = tw.rollout(h0, E=E, R=R, q_extra=eps * d)
        Hm = tw.rollout(h0, E=E, R=R, q_extra=-eps * d)
        dh = engine_tlm.tlm_rollout(tw, H, Es, dq=d)
    else:
        d = rng.uniform(0, 300.0, (A, T))
        qd = np.stack([tw.layer_sources(d[:, t]) for t in range(T)], axis=-1)
        Hp = tw.rollout(h0, E=E, R=R, q_extra=eps * qd)
        Hm = tw.rollout(h0, E=E, R=R, q_extra=-eps * qd)
        dh = engine_tlm.tlm_rollout(tw, H, Es, drate=d)    # layer_sources(d): abstraction d
    fd = (Hp - Hm) / (2 * eps)
    assert _rel(dh, fd) < 1e-6
    # the frozen-lift response misses the feedback by far more than the tolerance
    frozen = engine_tlm.tlm_rollout(
        tw, H, Es, frozen=True,
        **({"dEs": d} if which == "energy" else {"dq": d} if which == "source"
           else {"drate": d}))
    assert _rel(frozen, fd) > 1e-3


def test_frozen_tlm_equals_frozen_head_rollout_and_kernel():
    grid, tw, E, R, ge, h0 = _setup(T=18)
    A, T = E.shape
    H0 = tw.rollout(h0, E=E, R=R)
    Ex = np.zeros_like(E)
    Ex[4:9] = 5e4
    H1 = tw.rollout(h0, E=E, R=R, E_extra=Ex, frozen_head=H0[1, :, :-1])
    H0f = tw.rollout(h0, E=E, R=R, frozen_head=H0[1, :, :-1])
    dh = engine_tlm.tlm_rollout(tw, H0, tw.spread(E), dEs=tw.spread(Ex), frozen=True)
    assert _rel(dh, H1 - H0f) < 1e-10
    oi, ol = np.arange(0, A, 5), np.full(len(range(0, A, 5)), 1)
    K = engine.pump_kernel(engine.adjoint_greens(tw, oi, ol, T, dtype=np.float64),
                           tw.pump_weights(), dtype=np.float64)
    dq = engine.energy_rate_jacobian(tw, H0) * tw.spread(Ex)
    dw = engine_tlm.tlm_rollout(tw, H0, tw.spread(E), dEs=tw.spread(Ex), frozen=True,
                                obs=(ol, oi))
    assert _rel(dw, -engine.convolve(K, dq)) < 1e-10


def test_batched_columns_equal_single_runs_and_factor_variance():
    grid, tw, E, R, ge, h0 = _setup(T=15)
    A, T = E.shape
    H = tw.rollout(h0, E=E, R=R)
    Es = tw.spread(E)
    rng = np.random.default_rng(5)
    F = rng.standard_normal((5, A, T)) * 1e3
    oi, ol = np.array([0, 9, 21, 30]), np.array([1, 0, 1, 2])
    U = engine_tlm.tlm_factor_responses(tw, H, Es, F, "energy", (ol, oi), chunk=2)
    for j in range(5):
        uj = engine_tlm.tlm_rollout(tw, H, Es, dEs=F[j], obs=(ol, oi))
        assert _rel(U[j], uj) < 1e-12
    full = engine_tlm.tlm_rollout(tw, H, Es, dEs=F[0])
    assert _rel(full[ol, oi, 1:], U[0]) < 1e-12
    # draws regenerated by index give the same responses as the factor route
    xi = np.random.default_rng(9).standard_normal((40, 5))
    acc = np.zeros(U.shape[1:])
    for s, Rb in engine_tlm.tlm_draw_responses(
            tw, H, Es, lambda i: np.tensordot(xi[i], F, axes=1), 40, "energy", (ol, oi),
            chunk=16):
        acc += (Rb ** 2).sum(axis=-1)
        for k in range(Rb.shape[-1]):
            assert _rel(Rb[..., k], np.tensordot(xi[s + k], U, axes=1)) < 1e-10
    assert np.isfinite(engine.head_var_factors(U)).all()


def test_rivers_refused():
    grid, m, sc = _model(rivers=True)
    A = grid.n_active
    E, R, ge, h0 = _forcing(A, 6)
    tw = engine.SparseTwin(m, sc, ge)
    H = tw.rollout(h0, E=E, R=R)
    with pytest.raises(NotImplementedError):
        engine_tlm.tlm_rollout(tw, H, tw.spread(E), dEs=E)
